IF OBJECT_ID('DBO.CONVERSATION', 'U') IS NULL
BEGIN
    CREATE TABLE DBO.CONVERSATION
    (
        C_ID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
        C_USER_ID VARCHAR(100) NOT NULL,
        C_TITLE VARCHAR(200) NOT NULL,
        C_DATE_GROUP VARCHAR(20) CHECK(C_DATE_GROUP IN('Hoy','Ayer','Últimos 7 días','Mes anterior')),
        C_PINNED BIT NOT NULL DEFAULT 0,
        C_ARCHIVED BIT NOT NULL DEFAULT 0,
        C_MESSAGE_COUNT INT NOT NULL DEFAULT 0,
        C_CATEGORY VARCHAR(100),
        C_MODEL_USED VARCHAR(50),
        C_CITED_SOURCES_COUNT INT NOT NULL DEFAULT 0,
        C_TOKEN_USED INT NOT NULL DEFAULT 0,
        C_CREATED_AT DATETIME2 NOT NULL,
        C_UPDATED_AT DATETIME2 NOT NULL
    );
END;

IF OBJECT_ID('DBO.MESSAGE', 'U') IS NULL
BEGIN
    CREATE TABLE DBO.MESSAGE(
        M_ID INT IDENTITY(1,1) NOT NULL PRIMARY KEY,
        M_CONVERSATION_ID INT NOT NULL,
        M_USER_ID VARCHAR(100) NOT NULL,
        M_SEQ INT NOT NULL,
        M_ROLE VARCHAR(20) NOT NULL CHECK(M_ROLE IN ('user', 'assistant')),
        M_CONTENT VARCHAR(MAX),
        M_SOURCES VARCHAR(MAX),
        M_STATUS VARCHAR(20) NOT NULL DEFAULT 'complete',
        M_FEEDBACK VARCHAR(10) NULL CHECK (M_FEEDBACK IN ('up','down')),
        M_MODEL_USED VARCHAR(50),
        M_TEMPERATURE NUMERIC(5,2) NOT NULL DEFAULT 0.5,
        M_REASONING_DEPTH VARCHAR(20) NOT NULL DEFAULT 'standard',
        M_INTERACTIVE_TYPE VARCHAR(50),
        M_CLAIM_DETAILS VARCHAR(50),
        M_TOKENS INT NOT NULL DEFAULT 0,
        M_BLOCKED BIT NOT NULL DEFAULT 0,
        M_TOOLS_USED VARCHAR(100),
        M_ATTACHED_DOCS VARCHAR(MAX),
        M_CREATED_AT DATETIME2 NOT NULL
    );
END;
